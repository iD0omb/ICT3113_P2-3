"""Assignment 2: why the cascade was not faster. Evidence from the speed-test service logs and .jtl files.

  python scripts/a2_cascade_analysis.py

Reads a2/results/speed/<config>/run<N>/ (results.jtl, requests.log, run.json) for llama, cascade-A and
cascade-B, and writes a2/results/cascade_analysis.md. Reads files only.

Definitions (all from the service log, Ollama's own durations, nanoseconds converted to seconds):
  compute    prompt_eval_duration + eval_duration of a model call: time the model was actually working,
             excluding time the request waited in Ollama's queue.
  call end   llama alone: log ts - db_ms. Cascade: the small call ends small_ms after the ticket's classify
             step started (ts - db_ms - classify_ms); the large call ends at ts - db_ms.
  compute interval  [call end - compute - load_duration, call end].
  overlap    two compute intervals of different tickets intersect by more than 10 ms (log timestamps are
             not exact, so smaller intersections are not counted).
  no-sharing estimate (per ticket)  mean compute of the small-model calls that overlapped no large-model
             call, plus, if the ticket was escalated, llama3.1:8b's compute on the same ticket in the
             llama-alone run with the same run number (same tickets in the same order). Ignores queueing.
Standard library only.
"""
import csv
import json
import statistics as st
import sys
from collections import Counter
from datetime import datetime
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SPEED = REPO / "a2" / "results" / "speed"
CONFIGS = ["llama", "cascade-A", "cascade-B"]
RUNS = [1, 2, 3]
TOL = 0.01


def compute(e, p=""):
    return (e.get(p + "prompt_eval_duration", 0) + e.get(p + "eval_duration", 0)) / 1e9


def load_run(cfg, n):
    d = SPEED / cfg / f"run{n}"
    run = json.loads((d / "run.json").read_text(encoding="utf-8-sig"))
    log = [json.loads(l) for l in (d / "requests.log").read_text(encoding="utf-8").splitlines() if l.strip()]
    tickets = sorted((e for e in log if e.get("run_id") == run["run_id"] and e.get("path") == "/tickets"),
                     key=lambda e: e["ticket_id"])
    with open(d / "results.jtl", encoding="utf-8", newline="") as f:
        jtl = list(csv.DictReader(f))
    if {r["ticket_id"] for r in jtl} != {str(e["ticket_id"]) for e in tickets}:
        sys.exit(f"{cfg} run {n}: .jtl ticket IDs do not match the service log")
    return run, tickets, jtl


def calls(cfg, tickets):
    """One entry per model call: (model, start, end, ticket entry, prefix)."""
    out = []
    for e in tickets:
        end = datetime.fromisoformat(e["ts"]).timestamp() - e.get("db_ms", 0) / 1e3
        if cfg == "llama":
            out.append(("llama", end - compute(e) - e.get("load_duration", 0) / 1e9, end, e, ""))
            continue
        s_end = end - e["classify_ms"] / 1e3 + e["small_ms"] / 1e3
        out.append(("qwen", s_end - compute(e, "small_") - e.get("small_load_duration", 0) / 1e9, s_end, e, "small_"))
        if e.get("escalated"):
            out.append(("llama", end - compute(e, "large_") - e.get("large_load_duration", 0) / 1e9, end, e, "large_"))
    return out


def overlaps(a, b):
    return a[3]["ticket_id"] != b[3]["ticket_id"] and a[1] < b[2] - TOL and b[1] < a[2] - TOL


def p95(values):
    s = sorted(values)
    return s[min(len(s) - 1, int(0.95 * len(s)))]


def fmt(x, unit=" s"):
    return f"{x:.2f}{unit}"


def main():
    data = {c: {n: load_run(c, n) for n in RUNS} for c in CONFIGS}
    llama_alone = {(n, i): compute(e) for n in RUNS for i, e in enumerate(data["llama"][n][1])}
    lines = ["# Cascade analysis: evidence from the speed tests", "",
             "Generated by `scripts/a2_cascade_analysis.py` from `a2/results/speed/*/run*/` (service logs, `.jtl`, "
             "`run.json`). Definitions are in the script's docstring. Reasoning: `a2/cascade_failure.md`.", ""]

    # 1. Headline latency (client side, .jtl)
    lines += ["## 1. End-to-end latency (JMeter `.jtl`, successful requests)", "",
              "| Configuration | p50 run 1 / 2 / 3 | Mean of p50 (SD) | Mean | Pooled p95 (n) |", "|---|---|---|---|---|"]
    for c in CONFIGS:
        runs = [[int(r["elapsed"]) / 1e3 for r in data[c][n][2] if r["success"] == "true"] for n in RUNS]
        p50s = [st.median(r) for r in runs]
        pooled = [x for r in runs for x in r]
        lines.append(f"| {c} | {' / '.join(fmt(p) for p in p50s)} | {fmt(st.mean(p50s))} ({st.stdev(p50s):.2f}) | "
                     f"{fmt(st.mean(pooled))} | {fmt(p95(pooled))} ({len(pooled)}) |")

    # 2. Escalation and what the small model predicted
    lines += ["", "## 2. Escalation under load and the small model's predictions", "",
              "| Configuration | Escalated (3 runs) | Break-even escalation | qwen3:4b predicted Debt collection | "
              "Credit card | Credit reporting |", "|---|---|---|---|---|---|"]
    q_alone_mean = {}
    for c in CONFIGS[1:]:
        t = [e for n in RUNS for e in data[c][n][1]]
        esc = sum(bool(e.get("escalated")) for e in t)
        small = Counter(e.get("small_category") for e in t)
        cs = [k for n in RUNS for k in calls(c, data[c][n][1])]
        q_alone = [compute(k[3], k[4]) for k in cs if k[0] == "qwen" and not any(m[0] == "llama" and overlaps(k, m) for m in cs)]
        q_alone_mean[c] = st.mean(q_alone)
        be = 1 - q_alone_mean[c] / st.mean(llama_alone.values())
        lines.append(f"| {c} | {esc}/{len(t)} ({esc / len(t):.0%}) | {be:.0%} | "
                     + " | ".join(f"{small[k]}/{len(t)} ({small[k] / len(t):.0%})" for k in
                                  ("Debt collection", "Credit card", "Credit reporting")) + " |")
    lines += ["", "Break-even = 1 − (qwen3:4b compute when not sharing the CPU) / (llama3.1:8b compute alone, "
              f"mean {fmt(st.mean(llama_alone.values()))}). Above it, the cascade's mean compute exceeds llama's."]

    # 3. Did the models run at the same time?
    lines += ["", "## 3. Model calls computing at the same time (compute intervals)", "",
              "| Configuration | Same model, two tickets at once | qwen3:4b calls overlapping a llama3.1:8b call | "
              "llama3.1:8b calls overlapping a qwen3:4b call |", "|---|---|---|---|"]
    speed_rows = []
    for c in CONFIGS:
        same, q_x, l_x, nq, nl = 0, 0, 0, 0, 0
        groups = {("qwen", False): [], ("qwen", True): [], ("llama", False): [], ("llama", True): []}
        for n in RUNS:
            cs = calls(c, data[c][n][1])
            for i, k in enumerate(cs):
                same += sum(1 for m in cs[i + 1:] if m[0] == k[0] and overlaps(k, m))
                shared = any(m[0] != k[0] and overlaps(k, m) for m in cs)
                if k[0] == "qwen":
                    nq += 1; q_x += shared
                else:
                    nl += 1; l_x += shared
                e, p = k[3], k[4]
                groups[(k[0], shared)].append((e[p + "prompt_eval_count"] / (e[p + "prompt_eval_duration"] / 1e9),
                                               e[p + "eval_count"] / (e[p + "eval_duration"] / 1e9), compute(e, p)))
        lines.append(f"| {c} | {same} | " + (f"{q_x}/{nq} ({q_x / nq:.0%})" if nq else "—") + " | "
                     + (f"{l_x}/{nl} ({l_x / nl:.0%})" if c != "llama" else "— (one model)") + " |")
        speed_rows.append((c, groups))
    lines += ["", "\"Same model, two tickets at once\" near 0 confirms `OLLAMA_NUM_PARALLEL=1` held: each model "
              "worked on one ticket at a time. The few counted are within log-timestamp error."]

    lines += ["", "## 4. Model speed alone vs while the other model was computing", "",
              "| Configuration | Model | Not sharing: prompt tok/s, generation tok/s, compute (n) | "
              "Sharing: prompt tok/s, generation tok/s, compute (n) | Compute slower by |", "|---|---|---|---|---|"]
    for c, groups in speed_rows:
        for m in ("qwen", "llama"):
            a, b = groups[(m, False)], groups[(m, True)]
            if not a:
                continue
            desc = lambda g: (f"{st.median(x[0] for x in g):.0f}, {st.median(x[1] for x in g):.1f}, "
                              f"{fmt(st.mean(x[2] for x in g))} ({len(g)})") if g else "—"
            slow = f"{st.mean(x[2] for x in b) / st.mean(x[2] for x in a) - 1:.0%}" if b else "—"
            lines.append(f"| {c} | {'qwen3:4b' if m == 'qwen' else 'llama3.1:8b'} | {desc(a)} | {desc(b)} | {slow} |")
    lines += ["", "Compute in this table is per call; tickets differ in length between the groups, so the tok/s "
              "columns are the like-for-like comparison."]

    # 5. No-sharing estimate
    lines += ["", "## 5. Per-ticket compute: measured vs estimated with no sharing", "",
              "| Configuration | Measured mean / median | No-sharing estimate mean / median | llama3.1:8b alone mean / median |",
              "|---|---|---|---|"]
    la = list(llama_alone.values())
    for c in CONFIGS[1:]:
        actual, est = [], []
        for n in RUNS:
            for i, e in enumerate(data[c][n][1]):
                actual.append(compute(e, "small_") + (compute(e, "large_") if e.get("escalated") else 0))
                est.append(q_alone_mean[c] + (llama_alone[(n, i)] if e.get("escalated") else 0))
        lines.append(f"| {c} | {fmt(st.mean(actual))} / {fmt(st.median(actual))} | {fmt(st.mean(est))} / "
                     f"{fmt(st.median(est))} | {fmt(st.mean(la))} / {fmt(st.median(la))} |")
    lines += ["", "The estimate removes only the CPU sharing. It does not model queueing, which would also change."]

    # 6. Load and stability
    lines += ["", "## 6. How busy the machine was, and whether latency settled", "",
              "| Configuration | Model compute / run duration, run 1 / 2 / 3 | Median latency by third of run (s), run 1; 2; 3 |",
              "|---|---|---|"]
    for c in CONFIGS:
        busy, thirds = [], []
        for n in RUNS:
            _, tickets, jtl = data[c][n]
            work = sum(compute(e) if c == "llama" else compute(e, "small_") + (compute(e, "large_") if e.get("escalated") else 0)
                       for e in tickets)
            start = min(int(r["timeStamp"]) for r in jtl)
            end = max(int(r["timeStamp"]) + int(r["elapsed"]) for r in jtl)
            busy.append(work / ((end - start) / 1e3))
            el = [int(r["elapsed"]) / 1e3 for r in sorted(jtl, key=lambda r: int(r["timeStamp"]))]
            k = len(el) // 3
            thirds.append("/".join(f"{st.median(el[i * k:(i + 1) * k if i < 2 else None]):.1f}" for i in range(3)))
        lines.append(f"| {c} | {' / '.join(f'{b:.0%}' for b in busy)} | {'; '.join(thirds)} |")
    lines += ["", "Run duration: first request sent to last response received (`.jtl`). In the cascades this "
              "sums both models' compute, including the stretches where they computed at the same time (section 3). "
              "No third of a run is consistently higher than the others, so no queue built up over a run."]

    out = REPO / "a2" / "results" / "cascade_analysis.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    print("\n".join(lines))
    print(f"-> {out}")


if __name__ == "__main__":
    main()
