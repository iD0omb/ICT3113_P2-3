"""Assignment 2, Step 2: simulate category-based cascades on the TUNING set only.

  python scripts/a2_simulate.py

Rule simulated (A2 brief, example method 1): the small model classifies every ticket; if its predicted
category is in the escalate set, the ticket goes to llama3.1:8b, whose answer is final; otherwise the
small model's answer is final. A failed small-model request always escalates.

Uses each model's Assignment 1 accuracy run, which is deterministic (temperature 0, fixed seed), so a
model's answer to a ticket is the answer the live cascade will get. Latency estimates use each ticket's
measured A1 single-request latency: small model always, plus llama when escalated (no queueing, no
routing overhead). Test rows are never read for anything except the limits already fixed in Step 1.

Writes a2/results/simulation_tuning.md. Reads files only.
"""
import csv
import json
import statistics
import sys
from itertools import combinations
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from accuracy_run import CATEGORIES, REPO  # noqa: E402

LARGE = "llama3_1_8b"
SMALLS = ["qwen3_4b", "gemma3_4b"]
OUT = REPO / "a2" / "results" / "simulation_tuning.md"
SHORT = {"Bank account or service": "Bank", "Consumer loan": "Loan", "Credit card": "Card",
         "Credit reporting": "CredRep", "Debt collection": "Debt", "Money transfer or service": "Money",
         "Mortgage": "Mort"}


def read_csv(path):
    with open(path, encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f))


def answers(model, tuning):
    rows = read_csv(REPO / "results" / model / "accuracy" / "accuracy.csv")
    return {r["ticket_number"]: r for r in rows if r["ticket_number"] in tuning}


def simulate(small, large, tickets, escalate):
    out = []
    for t in tickets:
        s, l = small[t], large[t]
        esc = s["status"] != "201" or s["predicted"] in escalate
        final = l if esc else s
        latency = float(s["latency_ms"]) + (float(l["latency_ms"]) if esc else 0.0)
        out.append({"golden": s["golden"], "escalated": esc, "correct": final["correct"] == "1",
                    "small_correct": s["correct"] == "1", "latency": latency})
    return out


def summarise(sim, limits):
    n = len(sim)
    esc = [x for x in sim if x["escalated"]]
    kept = [x for x in sim if not x["escalated"]]
    overall = sum(x["correct"] for x in sim)
    per_cat = {}
    for c in CATEGORIES:
        in_c = [x for x in sim if x["golden"] == c]
        per_cat[c] = (sum(x["correct"] for x in in_c), len(in_c))
    fails = [c for c, (k, m) in per_cat.items() if m and 100 * k / m < limits[c] - 1e-9]
    overall_ok = 100 * overall / n >= limits["overall"] - 1e-9
    lat = [x["latency"] for x in sim]
    return {
        "esc_n": len(esc), "esc_frac": len(esc) / n, "overall": overall, "n": n,
        "per_cat": per_cat, "fails": fails, "pass": overall_ok and not fails, "overall_ok": overall_ok,
        "slipped": sum(not x["correct"] for x in kept), "kept_n": len(kept),
        "esc_acc": (sum(x["correct"] for x in esc), len(esc)), "kept_acc": (sum(x["correct"] for x in kept), len(kept)),
        "mean_ms": statistics.mean(lat), "median_ms": statistics.median(lat),
    }


def main():
    split = read_csv(REPO / "a2" / "golden_split.csv")
    tuning = {r["ticket_number"] for r in split if r["set"] == "tuning"}
    limits = json.loads((REPO / "a2" / "results" / "limits.json").read_text(encoding="utf-8"))["limits_pct"]
    large = answers(LARGE, tuning)
    tickets = sorted(tuning, key=int)
    large_lat = [float(large[t]["latency_ms"]) for t in tickets]
    ref = {"mean": statistics.mean(large_lat), "median": statistics.median(large_lat),
           "correct": sum(large[t]["correct"] == "1" for t in tickets)}

    lines = ["# Cascade simulation on the tuning set (75 tickets)", "",
             "Generated by `scripts/a2_simulate.py` from Assignment 1 accuracy runs, tuning rows only. "
             "Limits from `a2/results/limits.json` (test-set top model). Latency = measured A1 single-request "
             "time of the small model, plus llama's when escalated; no queueing.", "",
             f"**llama3.1:8b alone (tuning):** {ref['correct']}/75 = {100 * ref['correct'] / 75:.1f}%, "
             f"mean {ref['mean'] / 1000:.2f} s, median {ref['median'] / 1000:.2f} s", ""]

    for small_name in SMALLS:
        small = answers(small_name, tuning)
        small_lat = [float(small[t]["latency_ms"]) for t in tickets]
        mean_small = statistics.mean(small_lat)
        lines += [f"## {small_name} → llama3.1:8b", "",
                  f"Small model alone: {sum(small[t]['correct'] == '1' for t in tickets)}/75, mean "
                  f"{mean_small / 1000:.2f} s. Break-even escalation fraction (mean latency): "
                  f"{1 - mean_small / ref['mean']:.0%}.", "",
                  "### Small model by predicted category (method-1 evidence)", "",
                  "| Predicted | Tickets | Small correct (precision) | llama correct on these | Gain if escalated |",
                  "|---|---|---|---|---|"]
        for c in CATEGORIES + [""]:
            these = [t for t in tickets if small[t]["predicted"] == c]
            if not these:
                continue
            sc = sum(small[t]["correct"] == "1" for t in these)
            lc = sum(large[t]["correct"] == "1" for t in these)
            lines.append(f"| {c or '(failed)'} | {len(these)} | {sc}/{len(these)} ({100 * sc / len(these):.0f}%) | "
                         f"{lc}/{len(these)} | {lc - sc:+d} |")

        results = []
        for k in range(len(CATEGORIES) + 1):
            for subset in combinations(CATEGORIES, k):
                s = summarise(simulate(small, large, tickets, set(subset)), limits)
                s["subset"] = subset
                results.append(s)

        passing = sorted((r for r in results if r["pass"]), key=lambda r: r["mean_ms"])
        lines += ["", f"### Settings that pass both limits on the tuning set: {len(passing)} of {len(results)}, "
                      "fastest first (top 12)", "",
                  "| Escalate when small predicts | Escalated | Accuracy | Wrong accepted | Esc. acc | Kept acc | "
                  "Mean s | Median s | vs llama mean |", "|---|---|---|---|---|---|---|---|---|"]
        for r in passing[:12]:
            lines.append(row(r, ref))
        near = sorted((r for r in results if not r["pass"] and r["esc_frac"] < 0.35),
                      key=lambda r: (len(r["fails"]) + (not r["overall_ok"]), r["mean_ms"]))[:6]
        lines += ["", "### Closest failing settings under 35% escalation", "",
                  "| Escalate when small predicts | Escalated | Accuracy | Fails | Mean s | vs llama mean |",
                  "|---|---|---|---|---|---|"]
        for r in near:
            fails = ", ".join(SHORT[c] for c in r["fails"]) + ("" if r["overall_ok"] else " +overall")
            lines.append(f"| {label(r)} | {r['esc_n']} ({r['esc_frac']:.0%}) | {r['overall']}/75 "
                         f"({100 * r['overall'] / 75:.1f}%) | {fails} | {r['mean_ms'] / 1000:.2f} | "
                         f"{r['mean_ms'] / ref['mean'] - 1:+.0%} |")
        lines.append("")

    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    print("\n".join(lines))
    print(f"-> {OUT}")


def label(r):
    return " + ".join(SHORT[c] for c in r["subset"]) or "(nothing)"


def row(r, ref):
    ea, ka = r["esc_acc"], r["kept_acc"]
    return (f"| {label(r)} | {r['esc_n']} ({r['esc_frac']:.0%}) | {r['overall']}/75 ({100 * r['overall'] / 75:.1f}%) | "
            f"{r['slipped']}/{r['kept_n']} | {ea[0]}/{ea[1]} | {ka[0]}/{ka[1]} | {r['mean_ms'] / 1000:.2f} | "
            f"{r['median_ms'] / 1000:.2f} | {r['mean_ms'] / ref['mean'] - 1:+.0%} |")


if __name__ == "__main__":
    main()
