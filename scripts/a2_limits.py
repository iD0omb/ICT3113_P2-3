"""Assignment 2, Step 1: accuracy limits from the test set, and single-model verdicts.

  python scripts/a2_limits.py

Reuses each model's Assignment 1 accuracy run (results/<model>/accuracy/accuracy.csv), as the A2 brief
allows when digest, prompt, Ollama version and machine are unchanged (verified in the A2 memory check).
Scores only the rows of a2/golden_split.csv: test rows decide everything; tuning rows are reported for
cascade design only.

  Overall limit       = top model's test accuracy - 10 percentage points
  Per-category limit  = top model's test accuracy in that category - 15 percentage points
  A configuration passes a limit when its accuracy is at or above it. Failed requests count as wrong.

Writes a2/results/limits.md and a2/results/limits.json. Reads files only; changes nothing else.
"""
import csv
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from accuracy_run import CATEGORIES, REPO  # noqa: E402

TOP = "llama3_1_8b"
MODELS = ["llama3_1_8b", "gemma3_4b", "qwen3_4b", "deepseek-r1_1_5b"]
OVERALL_MARGIN, CATEGORY_MARGIN, SMALL = 10, 15, 10
OUT = REPO / "a2" / "results"


def read_csv(path):
    with open(path, encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f))


def score(rows):
    """Overall and per-category (correct, n) for a list of accuracy rows."""
    result = {"overall": (sum(int(r["correct"]) for r in rows), len(rows))}
    for c in CATEGORIES:
        in_cat = [r for r in rows if r["golden"] == c]
        result[c] = (sum(int(r["correct"]) for r in in_cat), len(in_cat))
    return result


def pct(correct, n):
    return 100 * correct / n if n else float("nan")


def cell(correct, n):
    return f"{pct(correct, n):.1f}% ({correct}/{n})"


def main():
    split = {r["ticket_number"]: r for r in read_csv(REPO / "a2" / "golden_split.csv")}
    scores = {}
    for model in MODELS:
        rows = read_csv(REPO / "results" / model / "accuracy" / "accuracy.csv")
        if len(rows) != len(split) or {r["ticket_number"] for r in rows} != set(split):
            sys.exit(f"{model}: accuracy.csv tickets do not match a2/golden_split.csv")
        mismatched = [r["ticket_number"] for r in rows if r["golden"] != split[r["ticket_number"]]["label"]]
        if mismatched:
            sys.exit(f"{model}: golden labels differ from the split for tickets {mismatched}")
        scores[model] = {s: score([r for r in rows if split[r["ticket_number"]]["set"] == s])
                         for s in ("test", "tuning")}

    top = scores[TOP]["test"]
    limits = {"overall": pct(*top["overall"]) - OVERALL_MARGIN}
    limits.update({c: pct(*top[c]) - CATEGORY_MARGIN for c in CATEGORIES})

    verdicts = {}
    for model in MODELS:
        s = scores[model]["test"]
        overall_ok = pct(*s["overall"]) >= limits["overall"] - 1e-9
        failed_cats = [c for c in CATEGORIES if pct(*s[c]) < limits[c] - 1e-9]
        verdicts[model] = {"overall_pass": overall_ok, "failed_categories": failed_cats,
                           "pass": overall_ok and not failed_cats}

    test_n = {c: top[c][1] for c in CATEGORIES}
    lines = [
        "# A2 accuracy limits and single-model verdicts (test set)", "",
        "Generated by `scripts/a2_limits.py` from `a2/golden_split.csv` and the Assignment 1 accuracy runs "
        "(`results/<model>/accuracy/accuracy.csv`), reused because digests, prompt, Ollama version and machine "
        "are unchanged (A2 memory check). Only test rows are scored. Failed requests count as wrong.", "",
        "## Limits (from llama3.1:8b on the test set)", "",
        f"- Top model test accuracy: **{cell(*top['overall'])}** → overall limit **{limits['overall']:.1f}%**",
        "", "| Category | Test tickets | llama3.1:8b | Limit (−15 pts) | Note |", "|---|---|---|---|---|"]
    for c in CATEGORIES:
        n = test_n[c]
        note = f"small: 1 ticket = {100 / n:.1f} pts" if n < SMALL else ""
        lines.append(f"| {c} | {n} | {cell(*top[c])} | {limits[c]:.1f}% | {note} |")

    lines += ["", "## Single models on the test set", "",
              "| Model | Overall | " + " | ".join(CATEGORIES) + " | Overall limit | Category limits | Verdict |",
              "|---" * (5 + len(CATEGORIES)) + "|"]
    for model in MODELS:
        s, v = scores[model]["test"], verdicts[model]
        cats = []
        for c in CATEGORIES:
            mark = " ✗" if c in v["failed_categories"] else ""
            cats.append(f"{cell(*s[c])}{mark}")
        fails = ", ".join(v["failed_categories"]) or "all pass"
        lines.append(f"| {model} | {cell(*s['overall'])} | " + " | ".join(cats) +
                     f" | {'pass' if v['overall_pass'] else 'FAIL'} | {fails} | "
                     f"**{'PASS' if v['pass'] else 'FAIL'}** |")
    lines += ["", "✗ = below that category's limit. The top model passes by definition (it sets the limits).", "",
              "## Tuning set (for cascade design only; not used for any verdict)", "",
              "| Model | Overall | " + " | ".join(CATEGORIES) + " |", "|---" * (2 + len(CATEGORIES)) + "|"]
    for model in MODELS:
        s = scores[model]["tuning"]
        lines.append(f"| {model} | {cell(*s['overall'])} | " + " | ".join(cell(*s[c]) for c in CATEGORIES) + " |")

    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "limits.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    (OUT / "limits.json").write_text(json.dumps({
        "top_model": TOP, "limits_pct": limits, "test_counts": test_n,
        "scores": {m: {s: {k: list(v) for k, v in d.items()} for s, d in sc.items()} for m, sc in scores.items()},
        "verdicts": verdicts,
    }, indent=2) + "\n", encoding="utf-8")
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    print("\n".join(lines))
    print(f"\n-> {OUT / 'limits.md'}, {OUT / 'limits.json'}")


if __name__ == "__main__":
    main()
