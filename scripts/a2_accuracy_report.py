"""Assignment 2, Step 4: accuracy results on the TEST set for every configuration (Slide 4).

  python scripts/a2_accuracy_report.py

Configurations and sources:
  llama3.1:8b, gemma3:4b, qwen3:4b, deepseek-r1:1.5b alone: the Assignment 1 accuracy runs
    (results/<model>/accuracy/accuracy.csv), reused as the A2 brief allows; test rows only.
  Cascade A, Cascade B: a2/results/accuracy/cascade-<A|B>/accuracy.csv from
    `accuracy_run.py --split test`, with that run's service log (requests.log, saved by a2_save_log.py).

For each configuration: overall accuracy (count, %) against the overall limit; per-category accuracy (count,
%) against each category's limit; a confusion matrix. For each cascade, from its service log: escalation
fraction, accuracy of escalated and accepted tickets, wrong answers accepted, and a reconciliation of every
accuracy row with its log line (same ticket ID, same category). Failed requests count as wrong.

Writes a2/results/accuracy_report.md. Reads files only.
"""
import argparse
import csv
import json
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from accuracy_run import CATEGORIES, REPO  # noqa: E402

SHORT = {"Bank account or service": "Bank", "Consumer loan": "Loan", "Credit card": "Card",
         "Credit reporting": "CredRep", "Debt collection": "Debt", "Money transfer or service": "Money",
         "Mortgage": "Mort"}
SMALL = 10


def read_csv(path):
    with open(path, encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f))


def cell(k, n):
    return f"{100 * k / n:.1f}% ({k}/{n})" if n else "—"


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--a2", type=Path, default=REPO / "a2", help="A2 folder (default: a2/)")
    parser.add_argument("--a1-results", type=Path, default=REPO / "results")
    args = parser.parse_args()

    split = {r["ticket_number"]: r for r in read_csv(args.a2 / "golden_split.csv")}
    test = {t for t, r in split.items() if r["set"] == "test"}
    limits = json.loads((args.a2 / "results" / "limits.json").read_text(encoding="utf-8"))["limits_pct"]
    configs = [(f"{m} alone", args.a1_results / d / "accuracy" / "accuracy.csv", None) for m, d in (
        ("llama3.1:8b", "llama3_1_8b"), ("gemma3:4b", "gemma3_4b"), ("qwen3:4b", "qwen3_4b"),
        ("deepseek-r1:1.5b", "deepseek-r1_1_5b"))]
    configs += [(f"Cascade {s}", args.a2 / "results" / "accuracy" / f"cascade-{s}" / "accuracy.csv",
                 args.a2 / "results" / "accuracy" / f"cascade-{s}" / "requests.log") for s in ("A", "B")]

    results, problems, missing = [], [], []
    for name, path, log_path in configs:
        if not path.exists():
            missing.append(f"{name}: {path.relative_to(REPO) if path.is_relative_to(REPO) else path} not found")
            continue
        rows = [r for r in read_csv(path) if r["ticket_number"] in test]
        got = {r["ticket_number"] for r in rows}
        if got != test or len(rows) != len(test):
            problems.append(f"{name}: has {len(rows)} test rows, expected exactly the {len(test)} test tickets")
            continue
        bad_label = [r["ticket_number"] for r in rows if r["golden"] != split[r["ticket_number"]]["label"]]
        if bad_label:
            problems.append(f"{name}: golden labels differ from the split for {bad_label}")
            continue
        res = {"name": name, "rows": rows, "source": path, "cascade": None}
        res["overall"] = (sum(int(r["correct"]) for r in rows), len(rows))
        res["cats"] = {c: (sum(int(r["correct"]) for r in rows if r["golden"] == c),
                           sum(r["golden"] == c for r in rows)) for c in CATEGORIES}
        res["fails"] = [c for c in CATEGORIES if res["cats"][c][1] and
                        100 * res["cats"][c][0] / res["cats"][c][1] < limits[c] - 1e-9]
        res["overall_ok"] = 100 * res["overall"][0] / res["overall"][1] >= limits["overall"] - 1e-9
        if log_path is not None:
            if not log_path.exists():
                problems.append(f"{name}: service log {log_path.name} not found next to accuracy.csv")
            else:
                res["cascade"] = cascade_details(name, rows, log_path, problems)
        results.append(res)

    lines = ["# A2 accuracy results on the test set (75 tickets)", "",
             "Generated by `scripts/a2_accuracy_report.py`. Single models reuse the Assignment 1 accuracy runs "
             "(same digests, prompt, Ollama version and machine), scored on test rows only. Cascades: live "
             "`POST /tickets` runs on the test rows (`a2/results/accuracy/cascade-*/`). Failed requests count "
             "as wrong. A configuration passes when it is at or above every limit.", "",
             f"Overall limit **{limits['overall']:.1f}%**. Category limits: "
             + ", ".join(f"{SHORT[c]} {limits[c]:.1f}%" for c in CATEGORIES) + ".", ""]
    if missing:
        lines += ["**Not available yet:** " + "; ".join(missing), ""]
    if problems:
        lines += ["**PROBLEMS:**", ""] + [f"- {p}" for p in problems] + [""]

    lines += ["## Overall and per category", "",
              "| Configuration | Overall | Overall limit | " + " | ".join(SHORT[c] for c in CATEGORIES)
              + " | Category limits | Verdict |", "|---" * (5 + len(CATEGORIES)) + "|"]
    for r in results:
        cats = [cell(*r["cats"][c]) + (" ✗" if c in r["fails"] else "") for c in CATEGORIES]
        verdict = "PASS" if r["overall_ok"] and not r["fails"] else "FAIL"
        lines.append(f"| {r['name']} | {cell(*r['overall'])} | {'pass' if r['overall_ok'] else 'FAIL'} | "
                     + " | ".join(cats) + f" | {', '.join(SHORT[c] for c in r['fails']) or 'all pass'} | "
                     f"**{verdict}** |")
    small = [f"{c} ({results[0]['cats'][c][1]} tickets, 1 ticket = {100 / results[0]['cats'][c][1]:.1f} pts)"
             for c in CATEGORIES if results and results[0]["cats"][c][1] < SMALL]
    lines += ["", "✗ = below that category's limit."]
    if small:
        lines.append("Too small for the per-category limit to be a fair test on its own: " + "; ".join(small) + ".")

    cascades = [r for r in results if r["cascade"]]
    if cascades:
        lines += ["", "## Cascade escalation (from the service log)", "",
                  "| Configuration | Escalated | Escalated tickets correct | Accepted tickets correct | "
                  "Wrong answers accepted | Small-model failures | Log reconciliation |", "|---|---|---|---|---|---|---|"]
        for r in cascades:
            c = r["cascade"]
            lines.append(f"| {r['name']} | {c['esc']}/{c['n']} ({100 * c['esc'] / c['n']:.0f}%) | {cell(*c['esc_acc'])} | "
                         f"{cell(*c['acc_acc'])} | {c['wrong_accepted']} | {c['small_failed']} | {c['recon']} |")

    lines += ["", "## Confusion matrices (rows: golden label, columns: answer)", ""]
    for r in results:
        cols = CATEGORIES + ["(failed)"]
        matrix = Counter((x["golden"], x["predicted"] or "(failed)") for x in r["rows"])
        lines += [f"### {r['name']}", "", "| golden \\ answer | " + " | ".join(SHORT.get(c, c) for c in cols) + " |",
                  "|---" * (1 + len(cols)) + "|"]
        for g in CATEGORIES:
            lines.append(f"| {SHORT[g]} | " + " | ".join(
                (f"**{matrix[(g, p)]}**" if g == p else str(matrix[(g, p)] or "")) for p in cols) + " |")
        lines.append("")

    out = args.a2 / "results" / "accuracy_report.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    print("\n".join(lines))
    print(f"-> {out}")
    sys.exit(1 if problems else 0)


def cascade_details(name, rows, log_path, problems):
    entries = [json.loads(l) for l in log_path.read_text(encoding="utf-8").splitlines() if l.strip()]
    tickets = [e for e in entries if e.get("path") == "/tickets"]
    by_id = {e["ticket_id"]: e for e in tickets if e.get("ticket_id") is not None}
    esc_rows, acc_rows, unmatched, mismatched = [], [], [], []
    for r in rows:
        e = by_id.get(int(r["ticket_id"])) if r["ticket_id"] else None
        if e is None:
            unmatched.append(r["ticket_number"])
            continue
        if e.get("category") != r["predicted"]:
            mismatched.append(r["ticket_number"])
        (esc_rows if e.get("escalated") else acc_rows).append(r)
    if len(tickets) != len(rows):
        problems.append(f"{name}: {len(tickets)} /tickets log lines for {len(rows)} accuracy rows")
    if unmatched:
        problems.append(f"{name}: no log line for tickets {unmatched}")
    if mismatched:
        problems.append(f"{name}: log category differs from accuracy.csv for tickets {mismatched}")
    configs = {e.get("configuration") for e in tickets}
    expected = f"cascade-{name.split()[-1]}"
    if configs != {expected}:
        problems.append(f"{name}: log configuration is {sorted(map(str, configs))}, expected {expected}")
    esc = sum(bool(e.get("escalated")) for e in tickets)
    return {
        "n": len(tickets), "esc": esc,
        "esc_acc": (sum(int(r["correct"]) for r in esc_rows), len(esc_rows)),
        "acc_acc": (sum(int(r["correct"]) for r in acc_rows), len(acc_rows)),
        "wrong_accepted": sum(not int(r["correct"]) for r in acc_rows),
        "small_failed": sum(e.get("escalation_reason") == "small model failed" for e in tickets),
        "recon": "all match" if not (unmatched or mismatched) and len(tickets) == len(rows) else "MISMATCH",
    }


if __name__ == "__main__":
    main()
